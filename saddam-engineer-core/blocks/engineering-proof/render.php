<?php
/**
 * Dynamic block render callback.
 *
 * @var array    $attributes Block attributes.
 * @var string   $content    Saved content, intentionally empty.
 * @var WP_Block $block      Block instance.
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

$title         = isset( $attributes['title'] ) ? sanitize_text_field( $attributes['title'] ) : __( 'Implemented in this WordPress system', 'spcore' );
$limit         = isset( $attributes['limit'] ) ? min( 12, max( 3, absint( $attributes['limit'] ) ) ) : 6;
$show_evidence = ! empty( $attributes['showEvidence'] );
$features      = array_slice( SPCore_Feature_Registry::all(), 0, $limit );
$wrapper       = get_block_wrapper_attributes( array( 'class' => 'spcore-engineering-proof' ) );
?>
<section <?php echo $wrapper; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by get_block_wrapper_attributes(). ?>>
	<div class="spcore-engineering-proof__intro">
		<p class="spcore-engineering-proof__eyebrow"><?php esc_html_e( 'Live WordPress implementation', 'spcore' ); ?></p>
		<h2><?php echo esc_html( $title ); ?></h2>
		<p><?php esc_html_e( 'Every item below maps to working code in the companion plugin and can be reviewed through the repository.', 'spcore' ); ?></p>
	</div>
	<div class="spcore-engineering-proof__grid">
		<?php foreach ( $features as $feature ) : ?>
			<article class="spcore-engineering-proof__card">
				<span><?php echo esc_html( $feature['category'] ); ?></span>
				<h3><?php echo esc_html( $feature['title'] ); ?></h3>
				<p><?php echo esc_html( $feature['description'] ); ?></p>
				<?php if ( $show_evidence ) : ?>
					<code><?php echo esc_html( $feature['evidence'] ); ?></code>
				<?php endif; ?>
			</article>
		<?php endforeach; ?>
	</div>
</section>
